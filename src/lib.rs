// FFI layer
/// Opaque runtime handle returned across FFI.
pub type AuthRuntimeHandle = c_void;

static RUNTIME: OnceLock<&'static AuthRuntime> = OnceLock::new();

fn to_cstring(value: &str) -> *mut c_char {
    // CString::new fails only on embedded NULs; our payloads are JSON and
    // never contain them. Fall back to an empty string defensively.
    match CString::new(value) {
        Ok(s) => s.into_raw(),
        Err(_) => CString::new("").expect("empty string has no NUL").into_raw(),
    }
}

fn error_json(err: &AuthenticationError) -> String {
    serde_json::to_string(err).unwrap_or_else(|_| {
        r#"{"kind":"internal","detail":"failed to encode error"}"#.to_string()
    })
}

/// Take a `*const c_char` argument (may be null → treated as empty).
unsafe fn arg(s: *const c_char) -> String {
    if s.is_null() {
        String::new()
    } else {
        CStr::from_ptr(s)
            .to_string_lossy()
            .into_owned()
    }
}

/// Initialize the process-wide authentication runtime.
///
/// * `store_url` / `login_url`: pass `""` for the Snap Store defaults
///   (`https://dashboard.snapcraft.io`, `https://login.ubuntu.com`).
/// * `permissions`: comma-separated attenuation list; `""` = the default
///   read/write set (same as `snapcraft login`).
/// * `storage_key`: key used with the credential store (and, by convention,
///   with Flutter Secure Storage).
///
/// Returns an opaque handle (keep it for the app's lifetime) or `null`
/// (error JSON in `out_err`).
#[no_mangle]
pub extern "C" fn auth_runtime_init(
    store_url: *const c_char,
    login_url: *const c_char,
    permissions: *const c_char,
    storage_key: *const c_char,
    out_err: *mut *mut c_char,
) -> *mut AuthRuntimeHandle {
    let result = (|| -> Result<*mut AuthRuntimeHandle> {
        if let Some(existing) = RUNTIME.get() {
            let p = *existing as *const AuthRuntime;
            return Ok(p as *mut AuthRuntimeHandle);
        }
        let mut config = AuthConfig::default();
        let store = unsafe { arg(store_url) };
        let login = unsafe { arg(login_url) };
        let perms = unsafe { arg(permissions) };
        let key = unsafe { arg(storage_key) };
        if !store.is_empty() {
            config.store_url = store;
        }
        if !login.is_empty() {
            config.login_url = login;
        }
        if !perms.is_empty() {
            config.permissions =
                perms.split(',').map(|s| s.trim().to_string()).filter(|s| !s.is_empty()).collect();
        }
        if !key.is_empty() {
            config.storage_key = key;
        }
        // `AuthRuntime::spawn` needs a Tokio context: use the shared
        // runtime from the FFI thread (it is multithreaded, so this is
        // safe and non-blocking).
        let handle = runtime::block_on(async { AuthRuntime::spawn(config) });
        let boxed = Box::new(handle);
        // Leak into a 'static reference parked in the process-wide slot so
        // `auth_runtime_get()` and null-handle calls keep working for the
        // lifetime of the app; the raw pointer handed to Dart aliases it.
        let leaked: &'static AuthRuntime = Box::leak(boxed);
        let ptr = leaked as *const AuthRuntime as *mut AuthRuntimeHandle;
        let _ = RUNTIME.set(leaked);
        Ok(ptr)
    })();
    match result {
        Ok(ptr) => {
            if !out_err.is_null() {
                unsafe { *out_err = std::ptr::null_mut() };
            }
            ptr
        }
        Err(e) => {
            if !out_err.is_null() {
                unsafe { *out_err = to_cstring(&error_json(&e)) };
            }
            std::ptr::null_mut()
        }
    }
}

/// Get the process-wide runtime handle (after [`auth_runtime_init`]).
/// Returns `null` when not yet initialized.
#[no_mangle]
pub extern "C" fn auth_runtime_get() -> *mut AuthRuntimeHandle {
    RUNTIME
        .get()
        .map(|r| {
            let p = *r as *const AuthRuntime;
            p as *mut AuthRuntimeHandle
        })
        .unwrap_or(std::ptr::null_mut())
}

fn with_runtime<T, F>(handle: *mut AuthRuntimeHandle, f: F) -> Result<T>
where
    F: FnOnce(&AuthRuntime) -> Result<T>,
{
    let runtime_ref: &AuthRuntime = if handle.is_null() {
        RUNTIME
            .get()
            .ok_or(AuthenticationError::NoActiveSession)?
    } else {
        unsafe { &*(handle as *const AuthRuntime) }
    };
    f(runtime_ref)
}

/// Current machine state, e.g. `"needs_2fa_code"`.
#[no_mangle]
pub extern "C" fn auth_state(handle: *mut AuthRuntimeHandle, out_err: *mut *mut c_char) -> *mut c_char {
    let result = with_runtime(handle, |rt| Ok(rt.state().as_str().to_string()));
    match result {
        Ok(s) => to_cstring(&s),
        Err(e) => {
            if !out_err.is_null() {
                unsafe { *out_err = to_cstring(&error_json(&e)) };
            }
            std::ptr::null_mut()
        }
    }
}

/// Number of unread machine events (for efficient polling).
#[no_mangle]
pub extern "C" fn auth_pending_events(handle: *mut AuthRuntimeHandle) -> u32 {
    with_runtime(handle, |rt| Ok(rt.pending_event_count() as u32)).unwrap_or(0)
}

/// Drain all machine events as JSON lines (`\n` joined; `""` when none).
///
/// Each line is the JSON encoding of a [`MachineEvent`], e.g.
/// `{"type":"needs_2fa_code"}` or
/// `{"type":"succeeded","email":"...","used_two_factor":true,"credentials_json":"..."}`.
#[no_mangle]
pub extern "C" fn auth_drain_events(handle: *mut AuthRuntimeHandle) -> *mut c_char {
    let result = with_runtime(handle, |rt| Ok(rt.drain_events()));
    match result {
        Ok(s) => to_cstring(&s),
        Err(e) => to_cstring(&format!(r#"{{"type":"failed","error":{}}}"#, error_json(&e))),
    }
}


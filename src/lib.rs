//! # snapstore-auth
//!
//! Interactive **OAuth2-style (Ubuntu One SSO) + 2FA login backend for the
//! Snap Store**, written in Rust and designed to be consumed from
//! **Flutter/Dart** over FFI.
//!
//! ```text
//! ┌──────────────────────── Flutter (Dart) ─────────────────────────┐
//! │  LoginScreen                                                     │
//! │    • state  = runtime.state()           (poll or stream)         │
//! │    • events = runtime.drain_events()   (JSON lines)              │
//! │    • on  NeedsCredentials → show email/password form             │
//! │    • on  Needs2FACode     → show TOTP/SMS input                  │
//! │    • on  Succeeded        → save credentials_json to             │
//! │                              flutter_secure_storage              │
//! └───────────────▲──────────────────────────│───────────────────────┘
//!                 │ MachineEvent (JSON)      │ UiEvent (typed args)
//!                 │                          ▼
//! ┌──────────────────────── Rust (FFI) ───────────────────────────────┐
//! │  AuthRuntime ──(mpsc)──▶ driver task (state machine, on Tokio)    │
//! │      │                     fetch /dev/api/acl/                  │
//! │      │                     POST discharge (401+2FA → pause)       │
//! │      │                     bind macaroons (HMAC-SHA256)           │
//! │      ▼                                                            │
//! │  CredentialsStore (InMemory)  ←  Dart persists to Secure Storage  │
//! └───────────────────────────────────────────────────────────────────┘
//! ```
//!
//! ## Why it is FFI-friendly (flutter_rust_bridge / UniFFI)
//!
//! * Every type crossing the boundary is a plain, owned, `Send + Sync`
//!   value (`String`, enums, serde-serializable structs) — no raw pointers,
//!   no lifetimes, no closures in the public API.
//! * Errors are one strongly-typed enum ([`AuthenticationError`]) that
//!   serializes to `{kind, detail}`; the library contains **no `unwrap()`
//!   on fallible paths**, so nothing panics across the boundary.
//! * All async work runs on a shared multithreaded Tokio runtime
//!   ([`runtime`]); the driver task suspends on channels while the UI
//!   thinks, so the Flutter main thread is never blocked.
//!
//! ## Interactive 2FA
//!
//! When Ubuntu One answers the discharge request with
//! `401 + twofactor-required`, the driver **yields**: it transitions to
//! [`MachineState::Needs2FACode`], emits [`MachineEvent::Needs2FACode`],
//! and parks on the command channel. Dart shows the code input and calls
//! `submit_2fa_code()`, which resumes the flow (fresh root macaroon +
//! discharge with `otp`).
//!
//! See [`auth_core`] for the protocol details (verified against
//! `canonical/snapcraft` → `craft-store` `login/_ubuntuone.py`).

